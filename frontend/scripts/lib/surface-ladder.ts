type Rung = Readonly<{
  ground: string;
  paint: string;
  edge: string;
  seam: string;
}>;

const HEADER = `/* A pane's ground and edge are its depth among panes, counted from the page or
   from the overlay it opens in. Zero specificity: a component's own paint wins. */
/* Generated by scripts/surface-ladder.ts, which takes a new selector as its
   argument; tokens.css holds the rungs. */
:root {
  --ground: var(--bgPage);
  --groundEdge: var(--ladder1Edge);
  --groundHover: var(--bgHover);
  --groundStrip: var(--bgStrip);
  --groundSeam: var(--borderSubtle);
}
`;

// One `:where()` per depth, laid out the way the formatter lays it out, so a
// generated sheet passes the lint lane unchanged.
function compound(list: readonly string[], at: number, of: number): string {
  const indent = of === 1 ? "  " : "    ";
  const items = list.map(
    (selector, index) =>
      `${indent}${selector}${index < list.length - 1 ? "," : ""}`,
  );
  const close = of === 1 ? ")" : "  )";
  return [`${at === 0 ? "" : "  "}:where(`, ...items, close].join("\n");
}

// var(--ground) resolves on the element that declares the shade, so every rule
// that sets --ground declares the shades again.
const SHADES = [
  ["Hover", "hover"],
  ["Strip", "strip"],
]
  .map(
    ([name, token]) =>
      `  --ground${name}: color-mix(\n    in srgb,\n` +
      `    var(--${token}Shade) var(--${token}Share),\n    var(--ground)\n  );\n`,
  )
  .join("");

function declarations(rung: Rung): string {
  return `  --ground: ${rung.ground};\n  --groundEdge: ${rung.edge};\n  --groundSeam: ${rung.seam};\n${SHADES}  background-color: ${rung.paint};\n`;
}

function rule(chain: readonly (readonly string[])[], rung: Rung): string {
  const selector = chain
    .map((list, at) => compound(list, at, chain.length))
    .join("\n");
  return `${selector} {\n${declarations(rung)}}\n`;
}

export function ladderSheet(
  surfaces: readonly string[],
  overlays: readonly string[],
): string {
  const page = PAGE_RUNGS.map((rung, depth) =>
    rule(Array(depth + 1).fill(surfaces), rung),
  );
  const overlay = PAGE_RUNGS.slice(1).map((rung, depth) =>
    rule([overlays, ...Array(depth + 1).fill(surfaces)], rung),
  );
  const pinned = PINNED_RUNGS.map(({ selector, level, takes }) => {
    const rung = PAGE_RUNGS[level - 1];
    const body =
      takes === "ground"
        ? declarations(rung)
        : `  --groundEdge: ${rung.edge};\n`;
    return `:where(${selector}) {\n${body}}\n`;
  });
  const hosts = compound(UNDERLAY_HOSTS, 0, 2);
  const underlay = `${hosts}\n${compound(surfaces, 1, 2)} {\n  background-color: var(--ground);\n}\n`;
  return [
    HEADER,
    ...page,
    rule([overlays], OVERLAY_RUNG),
    ...overlay,
    ...pinned,
    underlay,
  ].join("");
}

// The lists as the sheet states them, read from the level-1 rule and the
// overlay rule: one selector per line, the way ladderSheet writes them.
export function ladderLists(sheet: string): LadderLists {
  const listOf = (rung: Readonly<{ ground: string }>): string[] => {
    const at = sheet.indexOf(`  --ground: ${rung.ground};`);
    if (at < 0) {
      throw new Error(`surfaces.css has no rule for --ground: ${rung.ground}`);
    }
    const head = sheet.slice(0, at);
    const open = head.lastIndexOf("}\n") + 2;
    return head
      .slice(open)
      .split("\n")
      .map((line) => line.trim().replace(/,$/, ""))
      .filter((line) => line !== "" && !/^(:where\(|\) ?\{?$)/.test(line));
  };
  return {
    surfaces: listOf(PAGE_RUNGS[0]),
    overlays: listOf(OVERLAY_RUNG),
  };
}

export function editedLists(
  current: LadderLists,
  args: readonly string[],
): LadderLists {
  const listed = [...current.surfaces, ...current.overlays];
  if (args[0] === "--remove") {
    const gone = args.slice(1);
    const unknown = gone.filter((selector) => !listed.includes(selector));
    if (gone.length === 0 || unknown.length > 0) {
      throw new Error(`not on the ladder: ${unknown.join(", ") || "(none)"}`);
    }
    return {
      surfaces: current.surfaces.filter((one) => !gone.includes(one)),
      overlays: current.overlays.filter((one) => !gone.includes(one)),
    };
  }
  const split = args.indexOf("--");
  const surfaces = split < 0 ? args : args.slice(0, split);
  const overlays = split < 0 ? [] : args.slice(split + 1);
  const added = [...surfaces, ...overlays];
  const twice = added.filter(
    (selector, at) =>
      listed.includes(selector) || added.indexOf(selector) !== at,
  );
  if (twice.length > 0) {
    throw new Error(`already on the ladder: ${twice.join(", ")}`);
  }
  return {
    surfaces: [...current.surfaces, ...surfaces],
    overlays: [...current.overlays, ...overlays],
  };
}
