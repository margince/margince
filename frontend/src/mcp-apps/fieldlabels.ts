const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

/** isID reports whether a value is a record id, which a reader cannot use. */
export function isID(value: unknown): boolean {
  return typeof value === "string" && UUID.test(value);
}

/**
 * fieldLabel names a field. A field the catalog does not hold, a custom field
 * among them, reads as its wire name in words, never as the column itself.
 */
export function fieldLabel(name: string): string {
  const known = FIELD_LABELS[name];
  if (known !== undefined) return known;
  const words = name
    .replace(/^cf_/, "")
    .replace(/_id$/, "")
    .replaceAll("_", " ")
    .trim();
  return words === "" ? name : words.charAt(0).toUpperCase() + words.slice(1);
}
