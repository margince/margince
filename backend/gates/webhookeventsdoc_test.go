const webhookEventsDoc = "../docs/reference/webhook-events.md"

var updateWebhookEvents = flag.Bool("update-webhook-events", false,
	"rewrite docs/reference/webhook-events.md from backend/api/public-events.yaml")

const regenerateWebhookEvents = "cd backend && go test ./gates -run WebhookEventReference -update-webhook-events"

// eventSchema is the part of a public-events.yaml schema the reference prints.
type eventSchema struct {
	Description string                    `yaml:"description"`
	EventType   string                    `yaml:"x-event-type"`
	EntityType  string                    `yaml:"x-entity-type"`
	Version     int                       `yaml:"x-version"`
	Required    []string                  `yaml:"required"`
	Properties  map[string]eventFieldSpec `yaml:"properties"`
	Ref         string                    `yaml:"$ref"`
}

type eventFieldSpec struct {
	Type        any      `yaml:"type"`
	Format      string   `yaml:"format"`
	Description string   `yaml:"description"`
	Enum        []any    `yaml:"enum"`
	Ref         string   `yaml:"$ref"`
	Items       *yamlRef `yaml:"items"`
}

type yamlRef struct {
	Type any    `yaml:"type"`
	Ref  string `yaml:"$ref"`
}

func loadEventSchemas(t *testing.T) map[string]eventSchema {
	t.Helper()
	raw, err := os.ReadFile(publicEventsPath)
	if err != nil {
		t.Fatal(err)
	}
	var doc struct {
		Components struct {
			Schemas map[string]eventSchema `yaml:"schemas"`
		} `yaml:"components"`
	}
	if err := yaml.Unmarshal(raw, &doc); err != nil {
		t.Fatalf("parsing %s: %v", publicEventsPath, err)
	}
	return doc.Components.Schemas
}

// The webhook event reference is rendered from the published contract, so it
// lists every event a subscription may choose and every field it carries.
func TestWebhookEventReferenceMatchesTheContract(t *testing.T) {
	schemas := loadEventSchemas(t)
	want := renderWebhookEvents(schemas)
	if *updateWebhookEvents {
		if err := os.WriteFile(webhookEventsDoc, []byte(want), 0o600); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(webhookEventsDoc)
	if err != nil {
		t.Fatalf("%s is missing.\nGenerate it with:\n    %s", webhookEventsDoc, regenerateWebhookEvents)
	}
	if string(got) != want {
		t.Errorf("%s no longer describes the contract: %s.\nRegenerate with:\n    %s",
			webhookEventsDoc, firstDifference(string(got), want), regenerateWebhookEvents)
	}
}

// The floor under the parity check: the render is measured against the
// catalog, so a parser that dropped schemas cannot pass by rendering short.
func TestWebhookEventReferenceListsEverySubscribableEvent(t *testing.T) {
	page := renderWebhookEvents(loadEventSchemas(t))
	for eventType := range crmcontracts.PublicEventVersions {
		if !strings.Contains(page, "\n### `"+eventType+"`\n") {
			t.Errorf("the webhook event reference has no section for %s", eventType)
		}
	}
}

func renderWebhookEvents(schemas map[string]eventSchema) string {
	var b strings.Builder
	b.WriteString("# Webhook events\n\n")
	b.WriteString("<!-- Generated by backend/gates/webhookeventsdoc_test.go from backend/api/public-events.yaml. Do not edit by hand. -->\n\n")
	b.WriteString("Every event a webhook subscription can choose, and the fields each one carries.\n")
	b.WriteString("To change this page, change `backend/api/public-events.yaml` and regenerate:\n\n")
	b.WriteString("    " + regenerateWebhookEvents + "\n\n")
	b.WriteString("How delivery, signing and body templates work is in\n")
	b.WriteString("[explanation/outbound-webhooks.md](../explanation/outbound-webhooks.md). A body template reads\n")
	b.WriteString("these fields as `{{ data.<field> }}`, and the envelope fields below by their own path.\n\n")
	writeEnvelope(&b, schemas)
	events := eventSchemasByType(schemas)
	b.WriteString("## Events\n\n| Event | Record | Version |\n|---|---|---|\n")
	for _, s := range events {
		fmt.Fprintf(&b, "| [`%s`](#%s) | %s | %d |\n", s.EventType, anchor(s.EventType), s.EntityType, versionOf(s))
	}
	b.WriteString("\n")
	for _, s := range events {
		writeEvent(&b, s)
	}
	return b.String()
}

func writeEnvelope(b *strings.Builder, schemas map[string]eventSchema) {
	b.WriteString("## The envelope\n\nEvery delivery with the standard body is this envelope, with the event's own fields in `data`.\n\n")
	writeFields(b, schemas["PublicEventEnvelope"], "")
	for _, nested := range []struct{ name, prefix string }{
		{"PublicEventEntityRef", "entity."}, {"PublicEventActor", "actor."},
	} {
		writeFields(b, schemas[nested.name], nested.prefix)
	}
}

func eventSchemasByType(schemas map[string]eventSchema) []eventSchema {
	var out []eventSchema
	for _, s := range schemas {
		if s.EventType != "" {
			out = append(out, s)
		}
	}
	sort.Slice(out, func(i, j int) bool { return out[i].EventType < out[j].EventType })
	return out
}

func writeEvent(b *strings.Builder, s eventSchema) {
	fmt.Fprintf(b, "### `%s`\n\n", s.EventType)
	fmt.Fprintf(b, "Record: `%s` · version %d\n\n", s.EntityType, versionOf(s))
	if d := oneLine(s.Description); d != "" {
		b.WriteString(d + "\n\n")
	}
	if len(s.Properties) == 0 {
		b.WriteString("`data` is an empty object.\n\n")
		return
	}
	writeFields(b, s, "data.")
}

func writeFields(b *strings.Builder, s eventSchema, prefix string) {
	names := make([]string, 0, len(s.Properties))
	for name := range s.Properties {
		names = append(names, name)
	}
	sort.Strings(names)
	required := map[string]bool{}
	for _, r := range s.Required {
		required[r] = true
	}
	b.WriteString("| Field | Type | Always present | What it is |\n|---|---|---|---|\n")
	for _, name := range names {
		f := s.Properties[name]
		always := "no"
		if required[name] {
			always = "yes"
		}
		fmt.Fprintf(b, "| `%s%s` | %s | %s | %s |\n", prefix, name, fieldType(f), always,
			strings.ReplaceAll(oneLine(f.Description), "|", "\\|"))
	}
	b.WriteString("\n")
}

func fieldType(f eventFieldSpec) string {
	kind := typeName(f.Type)
	switch {
	case f.Ref != "":
		kind = refName(f.Ref)
	case kind == "array" && f.Items != nil:
		item := typeName(f.Items.Type)
		if f.Items.Ref != "" {
			item = refName(f.Items.Ref)
		}
		kind = "array of " + item
	}
	if f.Format != "" {
		kind += " (" + f.Format + ")"
	}
	if len(f.Enum) > 0 {
		values := make([]string, 0, len(f.Enum))
		for _, v := range f.Enum {
			if v != nil {
				values = append(values, fmt.Sprintf("`%v`", v))
			}
		}
		kind += ": " + strings.Join(values, ", ")
	}
	return kind
}

// typeName reads a 3.1 type, which is a word or a list that may name null.
func typeName(t any) string {
	switch v := t.(type) {
	case string:
		return v
	case []any:
		var kinds []string
		for _, k := range v {
			if s, ok := k.(string); ok && s != "null" {
				kinds = append(kinds, s)
			}
		}
		return strings.Join(kinds, " or ")
	}
	return "object"
}

func refName(ref string) string { return ref[strings.LastIndex(ref, "/")+1:] }

func versionOf(s eventSchema) int {
	if s.Version == 0 {
		return 1
	}
	return s.Version
}

func oneLine(s string) string { return strings.Join(strings.Fields(s), " ") }

// anchor is the heading id a renderer gives "### `deal.stage_changed`".
func anchor(eventType string) string {
	return strings.ReplaceAll(eventType, ".", "")
}
