// The work-area table the server reads matches the parity catalog's placement and the contract's WorkArea enum.
//
// The test that writes docs/reference/mcp-parity.md writes the table too, so a
// passport limited to some areas is held to the groups that page shows.

import (
	"encoding/json"
	"maps"
	"os"
	"slices"
	"testing"

	"gopkg.in/yaml.v3"

	"github.com/margince/margince/backend/internal/platform/workarea"
)

const workAreaTable = "internal/platform/workarea/workareas.json"

const workAreaNote = "Generated by `" + mcpParityCommand + "` from the placement in " +
	"gates/mcpparityplaces_test.go; do not edit by hand. Each operation an agent can call sits in the group " +
	"docs/reference/mcp-parity.md shows it in."

// workAreaFile places every operation that names an agent verb. It places each
// verb by the operations it serves. A verb in several areas is also placed by
// the record type that picks its operation.
func workAreaFile(t *testing.T, contract parityContract, report parityReport) []byte {
	t.Helper()
	file := workarea.File{
		Note: workAreaNote, Operations: map[string]string{},
		Verbs: map[string][]string{}, RecordCalls: map[string]map[string]string{},
	}
	for _, info := range parityGroupInfos {
		name := info.Passport
		if name == "" {
			name = info.Title
		}
		file.Areas = append(file.Areas, workarea.Area{Key: info.Key, Name: name, Choosable: info.Passport != ""})
	}
	for _, op := range report.Operations {
		tool := contract.routes[op.Path][op.Method].MCPTool
		if tool == nil {
			continue
		}
		file.Operations[op.OperationID] = op.Group
		if !slices.Contains(file.Verbs[tool.Verb], op.Group) {
			file.Verbs[tool.Verb] = append(file.Verbs[tool.Verb], op.Group)
			slices.Sort(file.Verbs[tool.Verb])
		}
		if tool.RecordType == "" {
			continue
		}
		byType := file.RecordCalls[tool.Verb]
		if byType == nil {
			byType = map[string]string{}
			file.RecordCalls[tool.Verb] = byType
		}
		if placed, seen := byType[tool.RecordType]; seen && placed != op.Group {
			t.Errorf("%s on %s serves %s %s in %q and another operation in %q, so a call cannot be placed by its "+
				"record type. Give the two one group in gates/mcpparityplaces_test.go.", tool.Verb, tool.RecordType,
				op.Method, op.Path, op.Group, placed)
		}
		byType[tool.RecordType] = op.Group
	}
	// A verb in one area needs no record type to place a call.
	for verb := range file.RecordCalls {
		if len(file.Verbs[verb]) < 2 {
			delete(file.RecordCalls, verb)
		}
	}
	payload, err := json.MarshalIndent(file, "", "  ")
	if err != nil {
		t.Fatalf("encoding the work-area table: %v", err)
	}
	return append(payload, '\n')
}

// The contract's WorkArea enum is what a client may send, so it must be the
// choosable areas, in the table's order, and nothing else.
func TestTheContractOffersTheChoosableWorkAreas(t *testing.T) {
	t.Parallel()
	raw, err := os.ReadFile(contractDocument)
	if err != nil {
		t.Fatalf("reading %s: %v", contractDocument, err)
	}
	var doc struct {
		Components struct {
			Schemas map[string]struct {
				Enum []string `yaml:"enum"`
			} `yaml:"schemas"`
		} `yaml:"components"`
	}
	if err := yaml.Unmarshal(raw, &doc); err != nil {
		t.Fatalf("parsing %s: %v", contractDocument, err)
	}
	var choosable []string
	for _, info := range parityGroupInfos {
		if info.Passport != "" {
			choosable = append(choosable, info.Passport)
		}
	}
	if len(choosable) < 2 {
		t.Fatalf("the parity groups name %d passport areas; a choice needs at least two", len(choosable))
	}
	var keys []string
	for _, area := range workarea.Choosable() {
		keys = append(keys, area.Key)
	}
	if got := doc.Components.Schemas["WorkArea"].Enum; !slices.Equal(got, keys) {
		t.Errorf("WorkArea in %s is %v; the embedded work-area table offers %v. Regenerate with %s, then make the "+
			"enum match.", contractDocument, got, keys, mcpParityCommand)
	}
	if len(keys) != len(choosable) {
		t.Errorf("the embedded table offers %d areas and the parity groups name %d. Regenerate with %s.",
			len(keys), len(choosable), mcpParityCommand)
	}
}

// Every verb the table places names only groups the table declares.
func TestTheWorkAreaTableNamesOnlyDeclaredAreas(t *testing.T) {
	t.Parallel()
	file := workarea.Embedded()
	declared := map[string]bool{}
	for _, area := range file.Areas {
		declared[area.Key] = true
	}
	if len(file.Operations) < parityOperationFloor/2 {
		t.Fatalf("the work-area table places %d operations, under half the parity floor; its walk lost them", len(file.Operations))
	}
	for _, verb := range slices.Sorted(maps.Keys(file.Verbs)) {
		for _, area := range file.Verbs[verb] {
			if !declared[area] {
				t.Errorf("%s is placed in %q, which the table does not declare", verb, area)
			}
		}
	}
	for op, area := range file.Operations {
		if !declared[area] {
			t.Errorf("%s is placed in %q, which the table does not declare", op, area)
		}
	}
}
