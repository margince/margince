-- Whether an activity's time is a real moment or only a date. A date-only
-- entry is stored at noon UTC of its date, and only this column says so.
--
-- NOT VALID, validated by the next migration in its own transaction, so the
-- scan holds SHARE UPDATE EXCLUSIVE rather than this ALTER's lock.
SET LOCAL lock_timeout = '3s';

-- A meeting holding its host's slot is compared by the hour, so it is never a day.
ALTER TABLE activity
    ADD COLUMN occurred_precision text DEFAULT 'instant' NOT NULL,
    ADD CONSTRAINT activity_occurred_precision_check
        CHECK (occurred_precision IN ('instant', 'day')) NOT VALID,
    ADD CONSTRAINT activity_day_holds_no_host_slot
        CHECK (occurred_precision = 'instant' OR NOT claims_host_slot) NOT VALID;

-- The last-activity clocks read a day entry by its date in the installation
-- zone. All four functions carry relstrength.LastActivityCountsSQL("a",
-- "now()") verbatim in every arm, held there by
-- backend/gates/lastactivitymeetingrule_test.go. Both clock triggers also fire
-- on occurred_precision, which that rule reads.
--
-- No stored clock needs a refold: every existing row is an instant, which the
-- rule reads as before.

CREATE OR REPLACE FUNCTION last_activity_of_deal(did uuid) RETURNS timestamptz
    LANGUAGE sql STABLE
    AS $$
  SELECT max(a.occurred_at)
    FROM activity_link l
    JOIN activity a ON a.id = l.activity_id AND a.archived_at IS NULL
     AND a.audience = 'workspace'
     AND a.origin NOT IN ('system_remediation', 'system_notice')
     AND (a.kind IN ('email','message','meeting','call','note') AND (a.kind <> 'meeting' OR (a.meeting_status IS NULL OR a.meeting_status IN ('booked','held'))) AND ((a.kind = 'meeting' AND (a.occurred_at <= greatest(now(), ((date_trunc('day', CAST(now() AS timestamptz) AT TIME ZONE COALESCE((SELECT st.value #>> '{}' FROM setting st WHERE st.key = 'installation.timezone'), 'UTC')) + interval '12 hours') AT TIME ZONE 'UTC')) AND (a.occurred_precision = 'day' AND a.occurred_at < ((date_trunc('day', CAST(now() AS timestamptz) AT TIME ZONE COALESCE((SELECT st.value #>> '{}' FROM setting st WHERE st.key = 'installation.timezone'), 'UTC')) + interval '12 hours') AT TIME ZONE 'UTC') OR a.occurred_precision = 'instant' AND a.occurred_at <= now()))) OR (a.kind <> 'meeting' AND (a.occurred_at <= greatest(now(), ((date_trunc('day', CAST(now() AS timestamptz) AT TIME ZONE COALESCE((SELECT st.value #>> '{}' FROM setting st WHERE st.key = 'installation.timezone'), 'UTC')) + interval '12 hours') AT TIME ZONE 'UTC')) AND (a.occurred_precision = 'day' OR a.occurred_at <= now())))))
   WHERE l.deal_id = did
$$;

