// Command gen-modelsetups writes frontend/src/lib/modelsetups.gen.ts: every
// preset under config/presets as the body PUT /ai/routing takes. The first-run
// screen binds a graded preset from it, never from a copy typed by hand.
// `make gen` runs it; its own test fails a stale file.
package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"log"
	"maps"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strings"

	"github.com/margince/margince/backend/internal/compose"
	"github.com/margince/margince/backend/internal/modules/ai"
)

var (
	presetsDir = flag.String("presets", "../config/presets", "the committed presets")
	outPath    = flag.String("out", "../frontend/src/lib/modelsetups.gen.ts", "generated frontend table destination")
	outGo      = flag.String("out-go", "internal/modules/ai/stockpresets_gen.go", "generated table of the presets that reorder a task")
)

func main() {
	flag.Parse()
	table, err := render(*presetsDir)
	if err != nil {
		log.Fatal(err)
	}
	//nolint:gosec // a committed source file every reader of the tree opens
	if err := os.WriteFile(*outPath, table, 0o644); err != nil {
		log.Fatalf("gen-modelsetups: writing %s: %v", *outPath, err)
	}
	stock, err := renderStock(*presetsDir)
	if err != nil {
		log.Fatal(err)
	}
	//nolint:gosec // a committed source file every reader of the tree opens
	if err := os.WriteFile(*outGo, stock, 0o644); err != nil {
		log.Fatalf("gen-modelsetups: writing %s: %v", *outGo, err)
	}
}

// renderStock writes the presets that reorder a task's rungs as Go strings. An
// install already bound to one of them, tier for tier, can then adopt the order
// a later release gave it (ai.RoutingConfig.WithStockTaskLadders).
func renderStock(dir string) ([]byte, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, fmt.Errorf("gen-modelsetups: reading %s: %w", dir, err)
	}
	var out bytes.Buffer
	out.WriteString("// Code generated by backend/tools/gen-modelsetups from config/presets. DO NOT EDIT.\n\npackage ai\n\n")
	out.WriteString("// stockPresets are the committed presets that reorder a task's rungs, by file name.\nvar stockPresets = map[string]string{\n")
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".yaml") {
			continue
		}
		raw, err := os.ReadFile(filepath.Join(dir, entry.Name())) //nolint:gosec // a preset of this tree
		if err != nil {
			return nil, fmt.Errorf("gen-modelsetups: reading %s: %w", entry.Name(), err)
		}
		cfg, err := ai.ParsePreset(raw)
		if err != nil {
			return nil, fmt.Errorf("gen-modelsetups: %s: %w", entry.Name(), err)
		}
		if len(cfg.TaskLadders) > 0 {
			fmt.Fprintf(&out, "\t%q: %q,\n", entry.Name(), raw)
		}
	}
	out.WriteString("}\n")
	return format.Source(out.Bytes())
}

// presetTitle is the `# Model setup:` line a preset names itself by.
var presetTitle = regexp.MustCompile(`(?m)^# Model setup: (\S.*\S)\s*$`)

// render reads every preset through the product's own preset reader and wire
// mapper, in file order, so the table changes only when a preset does.
func render(dir string) ([]byte, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, fmt.Errorf("gen-modelsetups: reading %s: %w", dir, err)
	}
	var out bytes.Buffer
	out.WriteString(header)
	ids := 0
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".yaml") {
			continue
		}
		raw, err := os.ReadFile(filepath.Join(dir, entry.Name())) //nolint:gosec // a preset of this tree
		if err != nil {
			return nil, fmt.Errorf("gen-modelsetups: reading %s: %w", entry.Name(), err)
		}
		title := presetTitle.FindSubmatch(raw)
		if title == nil {
			return nil, fmt.Errorf("gen-modelsetups: %s has no `# Model setup:` line to name it by", entry.Name())
		}
		body, err := compose.PresetRoutingBody(raw)
		if err != nil {
			return nil, fmt.Errorf("gen-modelsetups: %s: %w", entry.Name(), err)
		}
		fmt.Fprintf(&out, "  %s: {\n    title: %q,\n    routing: ", strings.TrimSuffix(entry.Name(), ".yaml"), title[1])
		if err := writeValue(&out, body, 2); err != nil {
			return nil, fmt.Errorf("gen-modelsetups: %s: %w", entry.Name(), err)
		}
		out.WriteString(",\n  },\n")
		ids++
	}
	if ids == 0 {
		return nil, fmt.Errorf("gen-modelsetups: no preset under %s, so the table would offer nothing", dir)
	}
	out.WriteString(footer)
	return out.Bytes(), nil
}

const header = `// Code generated by backend/tools/gen-modelsetups from config/presets. DO NOT EDIT.

import type { components } from "../api/schema";

/**
 * Every committed preset, by file name, as the body PUT /ai/routing takes:
 * parsed by the product's preset reader and mapped by the endpoint's own
 * mapper. The certification grades these setups, so a screen that binds one
 * binds a setup the tests have graded.
 */
export const MODEL_SETUPS = {
`

const footer = `} as const satisfies Record<
  string,
  { title: string; routing: components["schemas"]["AiRouting"] }
>;

export type ModelSetupId = keyof typeof MODEL_SETUPS;
`

// writeValue writes one JSON value as a TypeScript literal in the shape the
// frontend formatter keeps. An object takes one key per line, an array one line.
func writeValue(out *bytes.Buffer, raw json.RawMessage, depth int) error {
	trimmed := bytes.TrimSpace(raw)
	if len(trimmed) == 0 {
		return errors.New("an empty JSON value")
	}
	switch trimmed[0] {
	case '{':
		return writeObject(out, trimmed, depth)
	case '[':
		var items []json.RawMessage
		if err := json.Unmarshal(trimmed, &items); err != nil {
			return err
		}
		out.WriteString("[")
		for i, item := range items {
			if i > 0 {
				out.WriteString(", ")
			}
			if err := writeValue(out, item, depth+1); err != nil {
				return err
			}
		}
		out.WriteString("]")
		return nil
	default:
		out.Write(trimmed)
		return nil
	}
}

func writeObject(out *bytes.Buffer, raw json.RawMessage, depth int) error {
	var fields map[string]json.RawMessage
	if err := json.Unmarshal(raw, &fields); err != nil {
		return err
	}
	if len(fields) == 0 {
		out.WriteString("{}")
		return nil
	}
	indent := strings.Repeat("  ", depth+1)
	out.WriteString("{\n")
	for _, key := range slices.Sorted(maps.Keys(fields)) {
		out.WriteString(indent + tsKey(key) + ": ")
		if err := writeValue(out, fields[key], depth+1); err != nil {
			return err
		}
		out.WriteString(",\n")
	}
	out.WriteString(strings.Repeat("  ", depth) + "}")
	return nil
}

// identifier is a key the formatter writes bare.
var identifier = regexp.MustCompile(`^[A-Za-z_$][A-Za-z0-9_$]*$`)

func tsKey(key string) string {
	if identifier.MatchString(key) {
		return key
	}
	return fmt.Sprintf("%q", key)
}
