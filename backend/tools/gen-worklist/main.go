// Command gen-worklist compiles backend/api/worklist-kinds.yaml into the
// frontend's table of Worklist kinds: which kinds exist, the category each
// belongs to, and the message key that titles it.
//
// The table is for presentation only. Category, screen, rank and actions still
// arrive on every row from the API; the client uses this table to name a kind
// and to know it exists, never to decide how a row behaves.
//
// A kind whose title is missing from any locale fails generation, so a new kind
// cannot reach a reader as its own identifier.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"github.com/margince/margince/backend/internal/modules/worklist"
	"github.com/margince/margince/backend/internal/shared/kernel/events"
)

var (
	catalogPath = flag.String("catalog", "api/worklist-kinds.yaml", "the kind catalog to compile")
	localesDir  = flag.String("locales", "../frontend/src/i18n", "the directory holding the frontend locale tables")
	outPath     = flag.String("out-frontend", "../frontend/src/lib/worklistkinds.gen.ts", "generated frontend table destination")
)

// locales are the frontend's message tables; every kind needs its title in each.
var locales = []string{"en.ts", "de.ts", "vi.ts"}

func main() {
	flag.Parse()
	catalog, err := loadCatalog(*catalogPath)
	if err != nil {
		log.Fatal(err)
	}
	if err := checkTitles(catalog, *localesDir); err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*outPath, render(catalog), 0o644); err != nil {
		log.Fatalf("gen-worklist: writing %s: %v", *outPath, err)
	}
}

func loadCatalog(path string) (worklist.Catalog, error) {
	doc, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("gen-worklist: reading %s: %w", path, err)
	}
	return worklist.LoadCatalog(doc, events.Types())
}

// titleKey is the message key that names a kind. A core kind's lives under
// worklist.untitled; an extension kind's under its unit's own prefix, the one
// every unit's locale keys already carry.
func titleKey(kind worklist.Kind) string {
	if !kind.ExtensionKey {
		return "worklist.untitled." + kind.Name
	}
	unit, name, _ := strings.Cut(strings.TrimPrefix(kind.Name, "ext_"), ".")
	return "ext" + strings.ToUpper(unit[:1]) + unit[1:] + ".worklist." + name
}

func checkTitles(catalog worklist.Catalog, dir string) error {
	var missing []string
	for _, file := range locales {
		table, err := os.ReadFile(filepath.Join(dir, file))
		if err != nil {
			return fmt.Errorf("gen-worklist: reading locale %s: %w", file, err)
		}
		for _, name := range sortedNames(catalog) {
			key := titleKey(catalog[name])
			if !bytes.Contains(table, []byte(`"`+key+`":`)) {
				missing = append(missing, file+": "+key)
			}
		}
	}
	if len(missing) > 0 {
		return fmt.Errorf("gen-worklist: kinds with no title, add each key to its locale:\n  %s", strings.Join(missing, "\n  "))
	}
	return nil
}

func sortedNames(catalog worklist.Catalog) []string {
	names := make([]string, 0, len(catalog))
	for name := range catalog {
		names = append(names, name)
	}
	slices.Sort(names)
	return names
}

func render(catalog worklist.Catalog) []byte {
	var out bytes.Buffer
	out.WriteString(`// Code generated by backend/tools/gen-worklist from backend/api/worklist-kinds.yaml. DO NOT EDIT.

import type { components } from "../api/schema";

type Category = components["schemas"]["WorklistItem"]["category"];

/**
 * Every Worklist kind this build knows, with the category it belongs to and the
 * message key that titles it. For naming a row only: what a row does comes on
 * the row itself from the API.
 */
export const WORKLIST_KINDS = {
`)
	for _, name := range sortedNames(catalog) {
		kind := catalog[name]
		key := name
		if strings.ContainsAny(name, ".") {
			key = fmt.Sprintf("%q", name)
		}
		// One field per line, the shape the frontend formatter keeps.
		fmt.Fprintf(&out, "  %s: {\n    category: %q,\n    titleKey: %q,\n  },\n", key, kind.Category, titleKey(kind))
	}
	out.WriteString(`} as const satisfies Record<string, { category: Category; titleKey: string }>;

/** A kind name the table holds. */
export type WorklistKind = keyof typeof WORKLIST_KINDS;
`)
	return out.Bytes()
}
