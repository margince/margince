// The Go spelling of each YAML word, as compose/attention declares it.
var (
	goDestination = map[string]string{
		"today":         "destinationToday",
		"review":        "destinationReview",
		"system_health": "destinationSystemHealth",
		"none":          "destinationNone",
	}
	goOwner = map[string]string{
		"unstated":      "ownerUnstated",
		"named":         "ownerNamed",
		"nobody":        "ownerNobody",
		"the_reader":    "ownerTheReader",
		"from_the_deal": "ownerFromTheDeal",
		"unreadable":    "ownerUnreadable",
	}
)

// emitGo renders compose/attention/kinds_gen.go, the table the engine reads.
func emitGo(c catalog) ([]byte, error) {
	var b strings.Builder
	b.WriteString("// Code generated by tools/gen-worklist from api/worklist-kinds.yaml. DO NOT EDIT.\n\n")
	b.WriteString("package attention\n\n")
	b.WriteString("import crmcontracts \"github.com/margince/margince/backend/internal/contracts\"\n\n")
	b.WriteString("// worklistKinds holds one entry per Worklist source, as api/worklist-kinds.yaml declares it.\n")
	b.WriteString("var worklistKinds = map[crmcontracts.WorklistItemSource]worklistKind{\n")
	for _, name := range c.sortedNames() {
		k := c[name]
		answers := make([]string, 0, len(k.Owner))
		for _, answer := range k.Owner {
			answers = append(answers, goOwner[answer])
		}
		fmt.Fprintf(&b, "crmcontracts.WorklistItemSource%s: {\ncategory: %q,\ndestination: %s,\nowner: answers(%s),\npersonal: %t,\ndoneInPlace: %t,\n},\n",
			pascal(name), k.Category, goDestination[k.Destination], strings.Join(answers, ", "), *k.Personal, *k.DoneInPlace)
	}
	b.WriteString("}\n")
	formatted, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("gen-worklist: formatting the Go table: %w", err)
	}
	return formatted, nil
}

// pascal is oapi-codegen's spelling of an enum value in its constant's name, so
// a kind with no WorklistItem.source value fails to compile.
func pascal(name string) string {
	var out strings.Builder
	for word := range strings.SplitSeq(name, "_") {
		out.WriteString(strings.ToUpper(word[:1]) + word[1:])
	}
	return out.String()
}

// emitFrontend renders frontend/src/lib/worklistkinds.gen.ts: the kinds the
// client can name and the key that titles each. One field per line, the shape
// the frontend formatter keeps.
func emitFrontend(c catalog) []byte {
	var out bytes.Buffer
	out.WriteString(`// Code generated by backend/tools/gen-worklist from backend/api/worklist-kinds.yaml. DO NOT EDIT.

import type { MessageKey } from "../i18n/en";

/**
 * Every Worklist kind this build knows and the message key that titles it.
 * For naming a row only: what a row does comes on the row from the API.
 */
export const WORKLIST_KINDS = {
`)
	for _, name := range c.sortedNames() {
		fmt.Fprintf(&out, "  %s: {\n    titleKey: %q,\n  },\n", name, titleKey(name))
	}
	out.WriteString("} as const satisfies Record<string, { titleKey: MessageKey }>;\n")
	return out.Bytes()
}

func titleKey(name string) string {
	return "worklist.untitled." + name
}

// locales are the frontend's message tables; every kind needs its title in each.
var locales = []string{"en.ts", "de.ts", "vi.ts"}

// checkTitles refuses a kind whose title is missing from a locale, so a new
// kind cannot reach a reader as its own identifier.
func checkTitles(c catalog, dir string) error {
	var missing []string
	for _, file := range locales {
		table, err := os.ReadFile(filepath.Join(dir, file)) //nolint:gosec // a locale file of this tree, named by the list above
		if err != nil {
			return fmt.Errorf("gen-worklist: reading locale %s: %w", file, err)
		}
		for _, name := range c.sortedNames() {
			if !bytes.Contains(table, []byte(`"`+titleKey(name)+`":`)) {
				missing = append(missing, file+": "+titleKey(name))
			}
		}
	}
	if len(missing) > 0 {
		return fmt.Errorf("gen-worklist: kinds with no title, add each key to its locale:\n  %s", strings.Join(missing, "\n  "))
	}
	return nil
}
