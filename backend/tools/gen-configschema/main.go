// gen-configschema writes the model-binding $defs of config/margince.schema.json
// as Go, so the admin screen is served the schema the editor gate holds to the
// parser. The rest of that schema is committed as it stands; the settings
// registry is the source it is regenerated from next.
package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"os"
	"path/filepath"
)

func main() {
	routingGo := flag.String("routing-go", "", "the Go file that embeds the routing $defs for GET /ai/routing/schema")
	flag.Parse()
	if *routingGo == "" {
		fail(errors.New("gen-configschema needs -routing-go"))
	}
	if err := writeRoutingGo(*routingGo); err != nil {
		fail(err)
	}
}

// writeRoutingGo embeds the routing $defs in the ai module.
func writeRoutingGo(path string) error {
	var compact bytes.Buffer
	if err := json.Compact(&compact, routingDefs()); err != nil {
		return fmt.Errorf("gen-configschema: compacting the routing $defs: %w", err)
	}
	src := fmt.Sprintf("// Code generated by gen-configschema; DO NOT EDIT.\n\npackage ai\n\n"+
		"// routingSchemaJSON is the routing $defs of config/margince.schema.json.\n"+
		"const routingSchemaJSON = %q\n", compact.String())
	if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
		return fmt.Errorf("gen-configschema: creating the routing output directory: %w", err)
	}
	return os.WriteFile(path, []byte(src), 0o600)
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}
