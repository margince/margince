package main

import (
	"bytes"
	"errors"
	"fmt"
	"io"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
)

// generatedName is the file-name form of the marker: a JSON file has no
// comment to carry one.
var generatedName = regexp.MustCompile(`(_gen|\.gen|\.generated)\.[^./]+$`)

// generatedHead is the header form. Each alternative is a sentence the tree's
// generators write; a page that only mentions generated code says neither.
var generatedHead = regexp.MustCompile(`(?i)code generated .*do not edit|` +
	`\bgenerated(:| by| from| together)\b.*\bdo not edit|written by .*\bdo not edit|auto-generated by`)

// headLines is how far down a header may sit: a license block or a JSON
// opening brace comes first.
const headLines = 8

// headBytes bounds the read, so a multi-megabyte generated file costs no more
// than a short one.
const headBytes = 16 * 1024

// generatedOutputs is every tracked file that says a generator wrote it.
func generatedOutputs(root string, tracked []string) ([]string, error) {
	var outputs []string
	for _, path := range tracked {
		marked, err := carriesMarker(filepath.Join(root, path))
		if err != nil {
			return nil, err
		}
		if marked {
			outputs = append(outputs, path)
		}
	}
	return outputs, nil
}

func carriesMarker(path string) (bool, error) {
	if generatedName.MatchString(filepath.Base(path)) {
		return true, nil
	}
	head, err := readHead(path)
	if err != nil {
		return false, err
	}
	return generatedHead.Match(head), nil
}

// readHead reads the first headLines lines, from at most headBytes. A tracked
// symlink, or a file deleted from the work tree, has no head.
func readHead(path string) (head []byte, err error) {
	info, err := os.Lstat(path)
	if errors.Is(err, fs.ErrNotExist) || (err == nil && !info.Mode().IsRegular()) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	file, err := os.Open(path) // #nosec G304 -- a tracked path under the repository root
	if err != nil {
		return nil, err
	}
	defer func() {
		if closeErr := file.Close(); err == nil {
			err = closeErr
		}
	}()
	buf := make([]byte, headBytes)
	n, err := io.ReadFull(file, buf)
	if err != nil && !errors.Is(err, io.ErrUnexpectedEOF) && !errors.Is(err, io.EOF) {
		return nil, fmt.Errorf("reading %s: %w", path, err)
	}
	lines := bytes.SplitAfterN(buf[:n], []byte("\n"), headLines+1)
	return bytes.Join(lines[:min(len(lines), headLines)], nil), nil
}

// testNamed is a test function a header names as its writer.
var testNamed = regexp.MustCompile(`\bTest[A-Z]\w*`)

// writtenByOneOf reports whether the output's header names one of the tests.
func writtenByOneOf(root, output string, tests map[string]bool) (bool, error) {
	head, err := readHead(filepath.Join(root, output))
	if err != nil {
		return false, err
	}
	for _, name := range testNamed.FindAllString(string(head), -1) {
		if tests[name] {
			return true, nil
		}
	}
	return false, nil
}
