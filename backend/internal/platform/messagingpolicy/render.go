package messagingpolicy

import (
	"fmt"
	"go/format"
	"reflect"
	"strconv"
	"strings"
	"time"

	"github.com/margince/margince/backend/pkg/extension/messaging"
)

// GeneratedFile is the Go file a pack's rules are written to.
const GeneratedFile = "messagingrules_gen.go"

var messagingPath = reflect.TypeFor[messaging.Rules]().PkgPath()

// Render answers the Go source of package pkg declaring messagingRules(), the
// function the pack's New passes to Extension.Messaging. Every field of rules
// is written out as a keyed literal, so a gate reading the source sees the
// citations it would see in a hand-written pack.
func Render(pkg string, rules messaging.Rules) ([]byte, error) {
	w := &literalWriter{}
	literal, err := w.value(reflect.ValueOf(rules), true)
	if err != nil {
		return nil, err
	}
	imports := `"github.com/margince/margince/backend/pkg/extension/messaging"`
	if w.usesTime {
		imports = "\"time\"\n\n\t" + imports
	}
	src := fmt.Sprintf(`// Code generated by tools/gen-messaging-rules from policy/. DO NOT EDIT.

package %s

import (
	%s
)

// messagingRules is the rule set compiled from the policy folder: edit the
// Markdown there and run go generate.
func messagingRules() messaging.Rules {
	return %s
}
`, pkg, imports, literal)
	out, err := format.Source([]byte(src))
	if err != nil {
		return nil, fmt.Errorf("render: %w", err)
	}
	return out, nil
}

// literalWriter writes a value as a Go literal and notes the imports it needs.
type literalWriter struct {
	usesTime bool
}

// value writes v. typed asks for the type name on a struct literal, which a
// slice element leaves out.
func (w *literalWriter) value(v reflect.Value, typed bool) (string, error) {
	if d, isDuration := reflect.TypeAssert[time.Duration](v); isDuration {
		w.usesTime = true
		return duration(d), nil
	}
	if t, isTime := reflect.TypeAssert[time.Time](v); isTime {
		w.usesTime = true
		return instant(t), nil
	}
	switch v.Kind() {
	case reflect.String:
		return strconv.Quote(v.String()), nil
	case reflect.Bool:
		return strconv.FormatBool(v.Bool()), nil
	case reflect.Int:
		return strconv.FormatInt(v.Int(), 10), nil
	case reflect.Pointer:
		inner, err := w.value(v.Elem(), true)
		return "&" + inner, err
	case reflect.Slice:
		return w.slice(v)
	case reflect.Struct:
		return w.structure(v, typed)
	}
	return "", fmt.Errorf("render: %s has kind %s, which the generator cannot write", v.Type(), v.Kind())
}

func (w *literalWriter) slice(v reflect.Value) (string, error) {
	name, err := typeName(v.Type().Elem())
	if err != nil {
		return "", err
	}
	parts := make([]string, 0, v.Len())
	for i := range v.Len() {
		part, err := w.value(v.Index(i), false)
		if err != nil {
			return "", err
		}
		parts = append(parts, part)
	}
	return "[]" + name + "{" + strings.Join(parts, ", ") + "}", nil
}

func (w *literalWriter) structure(v reflect.Value, typed bool) (string, error) {
	var b strings.Builder
	if typed {
		name, err := typeName(v.Type())
		if err != nil {
			return "", err
		}
		b.WriteString(name)
	}
	b.WriteString("{\n")
	for i := range v.NumField() {
		field := v.Field(i)
		if field.IsZero() || (field.Kind() == reflect.Slice && field.Len() == 0) {
			continue
		}
		text, err := w.value(field, true)
		if err != nil {
			return "", fmt.Errorf("%s.%s: %w", v.Type().Name(), v.Type().Field(i).Name, err)
		}
		fmt.Fprintf(&b, "%s: %s,\n", v.Type().Field(i).Name, text)
	}
	b.WriteString("}")
	return b.String(), nil
}

// typeName answers how the generated file names t. Only the messaging
// package's types and plain strings are written, so one import serves.
func typeName(t reflect.Type) (string, error) {
	switch {
	case t.PkgPath() == messagingPath:
		return "messaging." + t.Name(), nil
	case t.PkgPath() == "" && t.Kind() == reflect.String:
		return "string", nil
	}
	return "", fmt.Errorf("render: %s is outside the messaging package", t)
}

// duration writes d in the largest unit that holds it exactly.
func duration(d time.Duration) string {
	for _, unit := range []struct {
		size time.Duration
		name string
	}{{time.Hour, "time.Hour"}, {time.Minute, "time.Minute"}, {time.Second, "time.Second"}} {
		if d%unit.size == 0 {
			return fmt.Sprintf("%d * %s", d/unit.size, unit.name)
		}
	}
	return fmt.Sprintf("time.Duration(%d)", int64(d))
}

// instant writes t as a time.Date call in UTC.
func instant(t time.Time) string {
	t = t.UTC()
	return fmt.Sprintf("time.Date(%d, time.%s, %d, %d, %d, %d, %d, time.UTC)",
		t.Year(), t.Month(), t.Day(), t.Hour(), t.Minute(), t.Second(), t.Nanosecond())
}
