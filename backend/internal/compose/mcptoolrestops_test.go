package compose

import (
	"encoding/json"
	"testing"
)

// e2eLLMRestOpsFile is the table the use-case lane reads to grade a REST call
// as the agent verb it runs.
const e2eLLMRestOpsFile = "../../../e2e/llm/rest_ops.json"

// The REST door of the use-case lane grades a call by the verb its operation
// declares. So the table is the contract's own. It holds every route an agent
// may call as a tool, keyed as the router registers it.
func TestTheLanesRestOperationTableIsPublished(t *testing.T) {
	operations := map[string]string{}
	for route, policy := range agentPolicies {
		if policy.Access == accessTool && policy.Tool != "" {
			operations[route] = policy.Tool
		}
	}
	if len(operations) == 0 {
		t.Fatal("no operation names an agent verb, so the lane would grade every REST call as unknown")
	}
	body, err := json.MarshalIndent(struct {
		Note       string            `json:"note"`
		Operations map[string]string `json:"operations"`
	}{Note: "Generated by go test ./internal/compose/ -run TestTheLanesRestOperationTableIsPublished -update-mcp-tool-coverage; do not edit by hand.", Operations: operations}, "", "  ")
	if err != nil {
		t.Fatalf("encoding the REST operation table: %v", err)
	}
	syncMCPToolCoverage(t, e2eLLMRestOpsFile, append(body, '\n'))
}
