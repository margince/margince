package compose

import (
	"encoding/json"
	"slices"
	"testing"
)

// e2eLLMRestOpsFile is the table the use-case lane reads to grade a REST call
// as the agent verb it runs.
const (
	e2eLLMRestOpsFile = "../../../e2e/llm/rest_ops.json"
	restOpsCommand    = "go test ./internal/compose/ -run TestTheLanesRestOperationTableIsPublished -update-mcp-tool-coverage"
)

// The REST door of the use-case lane grades a call by the verb its operation
// declares. So the table is the contract's own. It holds every route an agent
// may call as a tool, keyed as the router registers it. It also holds the record
// type of each typed route, such as PATCH /companies/{id}, which the MCP verb
// takes as record_type. A verb whose MCP arguments carry the record under
// fields takes the REST body there.
func TestTheLanesRestOperationTableIsPublished(t *testing.T) {
	operations, recordTypes := map[string]string{}, map[string]string{}
	for route, policy := range agentPolicies {
		if policy.Access == accessTool && policy.Tool != "" {
			operations[route] = policy.Tool
			if policy.RecordType != "" {
				recordTypes[route] = string(policy.RecordType)
			}
		}
	}
	if len(operations) == 0 || len(recordTypes) == 0 {
		t.Fatal("no operation names an agent verb or a record type, so the lane would grade REST calls short")
	}
	fieldsVerbs := []string{}
	for _, spec := range offeredSpecs(t) {
		var input struct {
			Properties map[string]json.RawMessage `json:"properties"`
		}
		if err := json.Unmarshal(spec.InputSchema, &input); err == nil && input.Properties["fields"] != nil {
			fieldsVerbs = append(fieldsVerbs, spec.Name)
		}
	}
	if !slices.Contains(fieldsVerbs, "update_record") {
		t.Fatalf("read %v as the verbs that take fields; update_record must be one", fieldsVerbs)
	}
	slices.Sort(fieldsVerbs)
	body, err := json.MarshalIndent(struct {
		Note        string            `json:"note"`
		Operations  map[string]string `json:"operations"`
		RecordTypes map[string]string `json:"record_types"`
		FieldsVerbs []string          `json:"fields_verbs"`
	}{Note: "Generated by " + restOpsCommand + "; do not edit by hand.", Operations: operations, RecordTypes: recordTypes, FieldsVerbs: fieldsVerbs}, "", "  ")
	if err != nil {
		t.Fatalf("encoding the REST operation table: %v", err)
	}
	syncMCPToolCoverage(t, e2eLLMRestOpsFile, append(body, '\n'), restOpsCommand)
}
