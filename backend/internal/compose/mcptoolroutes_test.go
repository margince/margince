// e2eLLMRoutesFile is the routing table the use-case lane reads, so a call to
// a router is graded as the verb its action runs.
const e2eLLMRoutesFile = "../../../e2e/llm/routes.json"

// verbRouters names the listed router fronting each verb a scenario may name.
func verbRouters(listed []mcp.ToolSpec) map[string]string {
	routes := map[string]string{}
	for _, spec := range listed {
		for _, action := range spec.Actions {
			routes[action.Verb] = spec.Name
		}
	}
	return routes
}

// routedName is the listed tool a scenario's verb is reached through.
func routedName(name string, routes map[string]string) string {
	if router, fronted := routes[name]; fronted {
		return router
	}
	return name
}

func routedNames(names []string, routes map[string]string) []string {
	out := make([]string, 0, len(names))
	for _, name := range names {
		out = append(out, routedName(name, routes))
	}
	return sortedCopy(out)
}

// routedCases credits a case's required verbs to the routers fronting them.
func routedCases(cases []caseRow, routes map[string]string) []caseRow {
	out := make([]caseRow, 0, len(cases))
	for _, c := range cases {
		c.Requires = routedNames(c.Requires, routes)
		groups := make([][]string, 0, len(c.RequiresOneOf))
		for _, group := range c.RequiresOneOf {
			groups = append(groups, routedNames(group, routes))
		}
		c.RequiresOneOf = groups
		out = append(out, c)
	}
	return out
}

// routeTable is one listed router as the lane reads it: the argument naming
// the action, and the verb each action runs.
type routeTable struct {
	Field   string            `json:"field,omitempty"`
	Actions map[string]string `json:"actions"`
}

// The use-case lane grades a router call as the verb it ran, by the table the
// served surface derives. A router whose action follows from the arguments
// named has no field, and the lane names it directly.
func TestTheLanesRoutingTableIsPublished(t *testing.T) {
	routers := map[string]routeTable{}
	for _, spec := range offeredSpecs(t) {
		if len(spec.Actions) == 0 {
			continue
		}
		table := routeTable{Field: spec.ActionField, Actions: map[string]string{}}
		for _, action := range spec.Actions {
			table.Actions[action.Action] = action.Verb
		}
		routers[spec.Name] = table
	}
	if len(routers) == 0 {
		t.Fatal("no listed router was found, so the lane would grade every router call as unknown")
	}
	names := make([]string, 0, len(routers))
	for name := range routers {
		names = append(names, name)
	}
	sort.Strings(names)
	body, err := json.MarshalIndent(struct {
		Note    string                `json:"note"`
		Routers map[string]routeTable `json:"routers"`
	}{Note: "Generated by " + mcpToolCoverageCommand + "; do not edit by hand.", Routers: routers}, "", "  ")
	if err != nil {
		t.Fatalf("encoding the routing table: %v", err)
	}
	syncMCPToolCoverage(t, e2eLLMRoutesFile, append(body, '\n'), mcpToolCoverageCommand)
}
