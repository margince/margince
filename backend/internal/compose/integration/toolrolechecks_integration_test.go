const toolChecksFile = "../../modules/agents/toolchecks.json"

// toolChecksNote is what the table says it holds.
const toolChecksNote = "Generated by TestTheToolRoleMatrixIsPublished (backend/internal/compose/integration). " +
	"Each verb lists the authority checks its admin call was asked, and where a gate refused the admin, the checks " +
	"of a role that ran it. A verb that picks its record by a kind argument keeps only the checks its call on " +
	"every kind was asked. A check stays only while no seeded role that lacks it got past it. " +
	"A tools/list offers an agent a verb only when its user holds every check. Do not edit by hand."

// toolCheckRecorder keeps, per verb, what the gates noted of the last call
// that ran it.
type toolCheckRecorder struct {
	mu   sync.Mutex
	last map[string]auth.RecordedCall
}

func newToolCheckRecorder() *toolCheckRecorder {
	return &toolCheckRecorder{last: map[string]auth.RecordedCall{}}
}

func (r *toolCheckRecorder) note(verb string, call auth.RecordedCall) {
	r.mu.Lock()
	defer r.mu.Unlock()
	r.last[verb] = call
}

// take hands over what the last call of verb was asked, once. A call that never
// reached the verb, such as a router refusing its action word, left nothing.
func (r *toolCheckRecorder) take(verb string) (auth.RecordedCall, bool) {
	r.mu.Lock()
	defer r.mu.Unlock()
	call, ok := r.last[verb]
	delete(r.last, verb)
	return call, ok
}

// toolChecksMeasure builds the table from the calls. The admin control is the
// row. Where a gate refused the admin, as an act only a narrower seat needs, a
// role that ran the call finishes it.
type toolChecksMeasure struct {
	control   map[string]agents.ToolChecksRow
	stopped   map[string]bool
	gated     map[string]bool
	ranByRole map[string][]string
	// paths are the checks each further path of a verb was asked, such as
	// the same call on another kind of record.
	paths map[string][][]string
}

func newToolChecksMeasure() toolChecksMeasure {
	return toolChecksMeasure{
		control: map[string]agents.ToolChecksRow{}, stopped: map[string]bool{}, gated: map[string]bool{},
		ranByRole: map[string][]string{}, paths: map[string][][]string{},
	}
}

// addPath records the checks another path of verb was asked.
func (m toolChecksMeasure) addPath(verb string, checks []string) {
	m.paths[verb] = append(m.paths[verb], checks)
}

// add records one call of verb. Two admin calls of one verb keep only the
// checks both were asked.
func (m toolChecksMeasure) add(verb string, control bool, run auth.RecordedCall, got apptest.MCPResult) {
	switch {
	case control:
		row := agents.ToolChecksRow{Checks: append([]string{}, run.Checks...)}
		if seen, twice := m.control[verb]; twice {
			row.Checks = slices.DeleteFunc(row.Checks, func(c string) bool { return !slices.Contains(seen.Checks, c) })
		}
		m.control[verb] = row
		m.stopped[verb] = m.stopped[verb] || got.IsError
		m.gated[verb] = m.gated[verb] || (got.IsError && len(run.Refused) > 0)
	case !got.IsError:
		if _, seen := m.ranByRole[verb]; !seen {
			m.ranByRole[verb] = append([]string{}, run.Checks...)
		}
	}
}

// rows is the table, and each verb whose checks are not all known. Such a
// verb's admin call stopped before a gate decided it, or a gate refused the
// admin and no role ran it. A row keeps only the checks every path was asked.
func (m toolChecksMeasure) rows() (map[string]agents.ToolChecksRow, []string) {
	out := map[string]agents.ToolChecksRow{}
	var partial []string
	for _, verb := range slices.Sorted(maps.Keys(m.control)) {
		row := m.control[verb]
		ran, someRoleRan := m.ranByRole[verb]
		switch {
		case !m.stopped[verb]:
		case m.gated[verb] && someRoleRan:
			row.Checks = slices.Compact(slices.Sorted(slices.Values(append(row.Checks, ran...))))
		default:
			partial = append(partial, verb)
		}
		for _, path := range m.paths[verb] {
			row.Checks = slices.DeleteFunc(row.Checks, func(c string) bool { return !slices.Contains(path, c) })
		}
		out[verb] = row
	}
	return out, partial
}

// provenBy keeps a check only while no seeded role lacking it ran the call. The
// call then degrades on that check instead of refusing, as an aggregate read
// renders a lane it may not read as withheld.
func provenBy(rows map[string]agents.ToolChecksRow, roles []seededRole, calls []toolRoleCall, verdicts map[string]toolRoleVerdicts) map[string]agents.ToolChecksRow {
	out := map[string]agents.ToolChecksRow{}
	for verb, row := range rows {
		row.Checks = slices.DeleteFunc(slices.Clone(row.Checks), func(name string) bool {
			check, err := auth.ParseCheck(name)
			return err == nil && slices.ContainsFunc(roles, func(role seededRole) bool {
				return !check.HeldBy(rolePrincipal(role)) && ranFor(role.key, verb, calls, verdicts)
			})
		})
		out[verb] = row
	}
	return out
}

// ranFor reports whether some call of verb ran for role.
func ranFor(role, verb string, calls []toolRoleCall, verdicts map[string]toolRoleVerdicts) bool {
	return slices.ContainsFunc(calls, func(call toolRoleCall) bool {
		return call.verb == verb && slices.Contains(verdicts[call.row].Allowed, role)
	})
}

// rolePrincipal is an agent on a passport of a human holding one seeded role's
// grants, as the sweep's passports are.
func rolePrincipal(role seededRole) principal.Principal {
	objects := map[string]principal.ObjectGrant{}
	for object, verbs := range role.objects {
		objects[object] = principal.ObjectGrant{
			Create: verbs["create"], Read: verbs["read"], Update: verbs["update"], Delete: verbs["delete"],
		}
	}
	return principal.Principal{
		Type: principal.PrincipalAgent, ID: "agent:" + role.key, PassportID: ids.NewV7(), OnBehalfOf: ids.NewV7(),
		Permissions: principal.Permissions{RoleKeys: []string{role.key}, Objects: objects, RowScope: principal.RowScope(role.rowScope)},
	}
}

// holdTheToolChecksTable holds the table the binary embeds to what the calls
// were asked, and rewrites it under the sweep's update flag. A verb whose
// checks are not all known fails: tools/list would offer it on a guess.
func holdTheToolChecksTable(t *testing.T, measured map[string]agents.ToolChecksRow, partial []string) {
	t.Helper()
	if len(measured) == 0 {
		t.Fatal("no admin call recorded a check, so the recorder is not wired to the calls")
	}
	if len(partial) > 0 {
		t.Errorf("%d verbs stopped before a gate decided their admin call, so their checks are not all known: %v", len(partial), partial)
	}
	rendered, err := json.MarshalIndent(agents.ToolChecksFile{Note: toolChecksNote, Verbs: measured}, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	rendered = append(rendered, '\n')
	if os.Getenv("UPDATE_MCP_TOOL_ROLES") != "" {
		if err := os.WriteFile(toolChecksFile, rendered, 0o600); err != nil {
			t.Fatal(err)
		}
		return
	}
	committed, err := os.ReadFile(toolChecksFile)
	if err != nil {
		t.Fatal(err)
	}
	if string(committed) != string(rendered) {
		t.Errorf("%s is not what the admin calls were asked. Run: UPDATE_MCP_TOOL_ROLES=1 make test-it DIR=backend/internal/compose/integration RUN=TestTheToolRoleMatrixIsPublished", toolChecksFile)
	}
}
