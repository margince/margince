const toolChecksFile = "../../modules/agents/toolchecks.json"

// partialCeiling is how many verbs may record a partial row, one whose admin
// call stopped before its last check. It only goes down; at zero every row is
// complete.
const partialCeiling = 7

// toolChecksNote is what the table says it holds.
const toolChecksNote = "Generated by TestTheToolRoleMatrixIsPublished (backend/internal/compose/integration). " +
	"Each verb lists the authority checks its admin call was asked. " +
	"A check stays only while no seeded role that lacks it got past it. " +
	"The complete flag is false where the call stopped for a reason that is not a role. " +
	"A tools/list offers an agent a verb only when its user holds every check. Do not edit by hand."

// toolCheckRecorder keeps, per verb, the checks of the last call that ran it.
type toolCheckRecorder struct {
	mu   sync.Mutex
	last map[string][]string
}

func newToolCheckRecorder() *toolCheckRecorder {
	return &toolCheckRecorder{last: map[string][]string{}}
}

func (r *toolCheckRecorder) note(verb string, checks []string) {
	r.mu.Lock()
	defer r.mu.Unlock()
	r.last[verb] = checks
}

// take hands over what the last call of verb was asked, once.
func (r *toolCheckRecorder) take(verb string) ([]string, bool) {
	r.mu.Lock()
	defer r.mu.Unlock()
	checks, ok := r.last[verb]
	delete(r.last, verb)
	return checks, ok
}

// toolChecksMeasure is the table as the admin control calls build it.
type toolChecksMeasure map[string]agents.ToolChecksRow

// add records what the admin call of verb was asked. A call that never reached
// the verb, such as a router refusing its action word, records nothing. Two
// calls of one verb keep only the checks both were asked.
func (m toolChecksMeasure) add(verb string, recorded *toolCheckRecorder, got apptest.MCPResult) {
	checks, ran := recorded.take(verb)
	if !ran {
		return
	}
	row := agents.ToolChecksRow{Checks: append([]string{}, checks...), Complete: !got.IsError}
	if seen, twice := m[verb]; twice {
		row.Checks = slices.DeleteFunc(row.Checks, func(c string) bool { return !slices.Contains(seen.Checks, c) })
		row.Complete = row.Complete && seen.Complete
	}
	m[verb] = row
}

// provenBy keeps a check only while no seeded role lacking it got past it. Such
// a role ran the call, or stopped where the admin stopped. The call then
// degrades on that check instead of refusing, as an aggregate read renders a
// lane it may not read as withheld.
func (m toolChecksMeasure) provenBy(roles []seededRole, calls []toolRoleCall, verdicts map[string]toolRoleVerdicts) toolChecksMeasure {
	out := toolChecksMeasure{}
	for verb, row := range m {
		row.Checks = slices.DeleteFunc(slices.Clone(row.Checks), func(name string) bool {
			check, err := auth.ParseCheck(name)
			return err == nil && slices.ContainsFunc(roles, func(role seededRole) bool {
				return !check.HeldBy(rolePrincipal(role)) && passedBy(role.key, verb, calls, verdicts)
			})
		})
		out[verb] = row
	}
	return out
}

// passedBy reports whether some call of verb was not refused on role's
// account: it ran, or it stopped for the reason the admin stopped for.
func passedBy(role, verb string, calls []toolRoleCall, verdicts map[string]toolRoleVerdicts) bool {
	return slices.ContainsFunc(calls, func(call toolRoleCall) bool {
		v := verdicts[call.row]
		if call.verb != verb {
			return false
		}
		admin, stopped := v.UnprovenReasons["admin"]
		return slices.Contains(v.Allowed, role) ||
			(stopped && admin != stopRefused && v.UnprovenReasons[role] == admin)
	})
}

// rolePrincipal is an agent holding one seeded role's grants.
func rolePrincipal(role seededRole) principal.Principal {
	objects := map[string]principal.ObjectGrant{}
	for object, verbs := range role.objects {
		objects[object] = principal.ObjectGrant{
			Create: verbs["create"], Read: verbs["read"], Update: verbs["update"], Delete: verbs["delete"],
		}
	}
	return principal.Principal{
		Type: principal.PrincipalAgent, ID: "agent:" + role.key,
		Permissions: principal.Permissions{RoleKeys: []string{role.key}, Objects: objects, RowScope: principal.RowScope(role.rowScope)},
	}
}

// holdTheToolChecksTable holds the table the binary embeds to what the admin
// control was asked, and rewrites it under the sweep's update flag.
func holdTheToolChecksTable(t *testing.T, measured toolChecksMeasure) {
	t.Helper()
	if len(measured) == 0 {
		t.Fatal("no admin call recorded a check, so the recorder is not wired to the calls")
	}
	var partial []string
	for _, verb := range slices.Sorted(maps.Keys(measured)) {
		if !measured[verb].Complete {
			partial = append(partial, verb)
		}
	}
	switch {
	case len(partial) > partialCeiling:
		t.Errorf("%d verbs record only the checks before the admin call stopped, above the ceiling of %d: %v", len(partial), partialCeiling, partial)
	case len(partial) < partialCeiling:
		t.Errorf("%d verbs record a partial row, below the ceiling of %d; lower partialCeiling to %d", len(partial), partialCeiling, len(partial))
	}
	rendered, err := json.MarshalIndent(agents.ToolChecksFile{Note: toolChecksNote, Verbs: measured}, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	rendered = append(rendered, '\n')
	if os.Getenv("UPDATE_MCP_TOOL_ROLES") != "" {
		if err := os.WriteFile(toolChecksFile, rendered, 0o600); err != nil {
			t.Fatal(err)
		}
		return
	}
	committed, err := os.ReadFile(toolChecksFile)
	if err != nil {
		t.Fatal(err)
	}
	if string(committed) != string(rendered) {
		t.Errorf("%s is not what the admin calls were asked. Run: UPDATE_MCP_TOOL_ROLES=1 make test-it DIR=backend/internal/compose/integration RUN=TestTheToolRoleMatrixIsPublished", toolChecksFile)
	}
}
