const toolChecksDir = "../../../modules/agents/toolchecks"

// toolChecksNote is what the table says it holds.
const toolChecksNote = "Generated by TestTheToolRoleMatrixIsPublished (backend/internal/compose/integration/toolrole). " +
	"Each verb lists the authority checks its admin call was asked, and where a gate refused the admin, the checks " +
	"of a role that ran it. A verb that picks its record by a kind argument holds the checks of each kind whose " +
	"admin call ran. A caller holding every check of one kind's call holds the row. A check that reads a,b is " +
	"held by holding either. A check stays only while no seeded role that lacks it got past it. " +
	"A tools/list offers an agent a verb only when its user holds every check. Do not edit by hand."

// toolCheckRecorder keeps, per verb and human, what the gates noted of the
// last call that ran it. Each role's passes run at once, each as its own user.
type toolCheckRecorder struct {
	mu   sync.Mutex
	last map[recordedKey]auth.RecordedCall
}

type recordedKey struct{ verb, human string }

func newToolCheckRecorder() *toolCheckRecorder {
	return &toolCheckRecorder{last: map[recordedKey]auth.RecordedCall{}}
}

func (r *toolCheckRecorder) note(verb string, call auth.RecordedCall) {
	r.mu.Lock()
	defer r.mu.Unlock()
	r.last[recordedKey{verb, call.Human}] = call
}

// take hands over what the last call of verb for human was asked, once. A
// call that never reached the verb, such as a router refusing its action
// word, left nothing.
func (r *toolCheckRecorder) take(verb, human string) (auth.RecordedCall, bool) {
	r.mu.Lock()
	defer r.mu.Unlock()
	call, ok := r.last[recordedKey{verb, human}]
	delete(r.last, recordedKey{verb, human})
	return call, ok
}

// toolChecksMeasure builds the table from the calls. The admin control is the
// row. Where a gate refused the admin, as an act only a narrower seat needs, a
// role that ran the call finishes it.
type toolChecksMeasure struct {
	control   map[string]toolroles.Checks
	stopped   map[string]bool
	gated     map[string]bool
	ranByRole map[string][]string
	// paths are the checks each further path of a verb that ran was asked,
	// such as the same call on another kind of record.
	paths map[string][][]string
}

func newToolChecksMeasure() toolChecksMeasure {
	return toolChecksMeasure{
		control: map[string]toolroles.Checks{}, stopped: map[string]bool{}, gated: map[string]bool{},
		ranByRole: map[string][]string{}, paths: map[string][][]string{},
	}
}

// addPath records the checks another path of verb was asked, for a path that
// ran. A path that stopped early was asked fewer, which would offer the verb to
// a caller no path admits.
func (m toolChecksMeasure) addPath(verb string, checks []string) {
	m.paths[verb] = append(m.paths[verb], checks)
}

// add records one call of verb. Two admin calls of one verb keep only the
// checks both were asked.
func (m toolChecksMeasure) add(verb string, control bool, run auth.RecordedCall, got apptest.MCPResult) {
	switch {
	case control:
		row := toolroles.Checks{Checks: append([]string{}, run.Checks...)}
		if seen, twice := m.control[verb]; twice {
			row.Checks = slices.DeleteFunc(row.Checks, func(c string) bool { return !slices.Contains(seen.Checks, c) })
		}
		m.control[verb] = row
		m.stopped[verb] = m.stopped[verb] || got.IsError
		m.gated[verb] = m.gated[verb] || (got.IsError && len(run.Refused) > 0)
	case !got.IsError:
		if _, seen := m.ranByRole[verb]; !seen {
			m.ranByRole[verb] = append([]string{}, run.Checks...)
		}
	}
}

// rows is the table, and each verb whose checks are not all known. Such a
// verb's admin call stopped before a gate decided it, or a gate refused the
// admin and no role ran it. A verb with further paths is offered to a caller
// who holds every check of some path.
func (m toolChecksMeasure) rows() (map[string]toolroles.Checks, []string) {
	out := map[string]toolroles.Checks{}
	var partial []string
	for _, verb := range slices.Sorted(maps.Keys(m.control)) {
		row := m.control[verb]
		ran, someRoleRan := m.ranByRole[verb]
		switch {
		case !m.stopped[verb]:
		case m.gated[verb] && someRoleRan:
			row.Checks = slices.Compact(slices.Sorted(slices.Values(append(row.Checks, ran...))))
		default:
			partial = append(partial, verb)
		}
		if paths := m.paths[verb]; len(paths) > 0 {
			row.Checks = someIsHeld(append([][]string{row.Checks}, paths...))
		}
		out[verb] = row
	}
	return out, partial
}

// provenBy keeps a check only while no seeded role lacking it ran the call. The
// call then degrades on that check instead of refusing, as an aggregate read
// renders a lane it may not read as withheld.
func provenBy(rows map[string]toolroles.Checks, roles []apptest.SeededRole, calls []toolRoleCall, verdicts map[string]toolRoleVerdicts) map[string]toolroles.Checks {
	out := map[string]toolroles.Checks{}
	for verb, row := range rows {
		row.Checks = slices.DeleteFunc(slices.Clone(row.Checks), func(name string) bool {
			check, err := auth.ParseCheck(name)
			return err == nil && slices.ContainsFunc(roles, func(role apptest.SeededRole) bool {
				return !check.HeldBy(role.AgentPrincipal()) && ranFor(role.Key, verb, calls, verdicts)
			})
		})
		out[verb] = row
	}
	return out
}

// ranFor reports whether some call of verb ran for role.
func ranFor(role, verb string, calls []toolRoleCall, verdicts map[string]toolRoleVerdicts) bool {
	return slices.ContainsFunc(calls, func(call toolRoleCall) bool {
		return call.verb == verb && slices.Contains(verdicts[call.row].Allowed, role)
	})
}

// holdTheToolChecksTable holds the table the binary embeds to what the calls
// were asked, and rewrites it under the sweep's update flag. A verb whose
// checks are not all known fails: tools/list would offer it on a guess.
func holdTheToolChecksTable(t *testing.T, measured map[string]toolroles.Checks, partial []string) {
	t.Helper()
	if len(measured) == 0 {
		t.Fatal("no admin call recorded a check, so the recorder is not wired to the calls")
	}
	if len(partial) > 0 {
		t.Errorf("%d verbs stopped before a gate decided their admin call, so their checks are not all known: %v", len(partial), partial)
	}
	takes := verbTakes(t)
	for verb, row := range measured {
		row.Verb, row.Takes = verb, takes[verb]
		measured[verb] = row
	}
	files, err := toolroles.Render(toolroles.Head{Note: toolChecksNote}, measured)
	if err != nil {
		t.Fatal(err)
	}
	holdTheFolder(t, toolChecksDir, files, "UPDATE_MCP_TOOL_ROLES=1 make test-roles")
}

// someIsHeld is the checks a caller holds when, and only when, it holds every
// check of some path. They are the checks all paths share, and one any-of
// check per pick of one other check from each path. A pick that holds another
// is dropped.
func someIsHeld(paths [][]string) []string {
	shared := slices.Clone(paths[0])
	for _, path := range paths[1:] {
		shared = slices.DeleteFunc(shared, func(c string) bool { return !slices.Contains(path, c) })
	}
	picks := [][]string{{}}
	for _, path := range paths {
		rest := slices.DeleteFunc(slices.Clone(path), func(c string) bool { return slices.Contains(shared, c) })
		if len(rest) == 0 {
			// This path asks only what all share, so holding those is enough.
			return slices.Sorted(slices.Values(shared))
		}
		var next [][]string
		for _, pick := range picks {
			for _, check := range rest {
				next = append(next, slices.Compact(slices.Sorted(slices.Values(append(slices.Clone(pick), strings.Split(check, ",")...)))))
			}
		}
		picks = next
	}
	out := slices.Clone(shared)
	for i, pick := range picks {
		wider := slices.ContainsFunc(picks[:i], func(other []string) bool { return slices.Equal(other, pick) }) ||
			slices.ContainsFunc(picks, func(other []string) bool { return len(other) < len(pick) && containsAll(pick, other) })
		if !wider {
			out = append(out, strings.Join(pick, ","))
		}
	}
	slices.Sort(out)
	return out
}

func containsAll(set, subset []string) bool {
	return !slices.ContainsFunc(subset, func(c string) bool { return !slices.Contains(set, c) })
}
