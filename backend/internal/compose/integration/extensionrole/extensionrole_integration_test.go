//go:build integration

// Package extensionrole measures the role cells of the verbs that read a
// composed extension unit. compose.RegisterExtensions holds for the whole test
// binary, so a unit registered in the role sweep's own package would reach
// every other suite there. This binary registers one synthetic unit, calls each
// verb as every seeded role, and commits the answers in measured.json. The
// role sweep reads that file for these verbs instead of calling them, so the
// published matrix holds one measured answer per cell.
package extensionrole

import (
	"encoding/json"
	"maps"
	"os"
	"slices"
	"sync"
	"testing"

	"github.com/margince/margince/backend/internal/compose"
	"github.com/margince/margince/backend/internal/compose/integration/apptest"
	"github.com/margince/margince/backend/internal/platform/auth"
	"github.com/margince/margince/backend/pkg/extension"
)

const (
	measuredFile = "measured.json"
	unitName     = "roleext"
	adminEmail   = "extension-role@fable.test"
	measuredNote = "Generated by TestTheExtensionVerbsRoleCellsArePublished (backend/internal/compose/integration/extensionrole), " +
		"which registers one synthetic unit in its own test binary. TestTheToolRoleMatrixIsPublished reads these verbs from here. " +
		"Do not edit by hand."
)

// measuredDoc is measured.json's shape, which the role sweep reads too.
type measuredDoc struct {
	Note  string                  `json:"note"`
	Roles []string                `json:"roles"`
	Verbs map[string]measuredVerb `json:"verbs"`
}

// measuredVerb is one verb's cells and the checks its admin call was asked.
type measuredVerb struct {
	Allowed []string `json:"allowed_for"`
	Refused []string `json:"refused_for"`
	Checks  []string `json:"checks"`
}

// unitArgs are what each verb that needs a composed unit is called with.
//
//craft:ignore naked-any an argument takes whichever JSON type its verb's schema names
var unitArgs = map[string]map[string]any{
	"get_extension_settings": {"name": unitName},
}

// routedCall is the tool a verb is served through and its arguments, with the
// router's action field set where a router serves it.
//
//craft:ignore naked-any an argument takes whichever JSON type its verb's schema names
func routedCall(t *testing.T, verb string) (string, map[string]any) {
	t.Helper()
	args := maps.Clone(unitArgs[verb])
	for _, spec := range compose.NewRegistry(nil, compose.SendPath{}).Specs() {
		if spec.Name == verb {
			return verb, args
		}
		for _, action := range spec.Actions {
			if action.Verb == verb {
				args[spec.ActionField] = action.Action
				return spec.Name, args
			}
		}
	}
	t.Fatalf("the registry serves no %s", verb)
	return "", nil
}

var (
	registerOnce sync.Once
	registerErr  error
)

func TestTheExtensionVerbsRoleCellsArePublished(t *testing.T) {
	registerOnce.Do(func() {
		registerErr = compose.RegisterExtensions([]extension.Extension{syntheticUnit()}, nil, nil)
	})
	if registerErr != nil {
		t.Fatalf("registering the synthetic unit: %v", registerErr)
	}
	var mu sync.Mutex
	recorded := map[string]auth.RecordedCall{}
	e := apptest.SetupAppWithOptions(t, compose.WithMCPConnector(), compose.WithFinanceSources(apptest.InsertOnlyRunner(t)),
		compose.WithToolChecksRecordedForTest(func(verb string, call auth.RecordedCall) {
			mu.Lock()
			defer mu.Unlock()
			recorded[verb] = call
		}))
	apptest.BootstrapWorkspaceSession(t, e, "Extension Role", adminEmail, "Admin")
	client := apptest.NewMCPClient(e, apptest.MCPBearerToken(t, e, "extension role", "read", "write"))
	maps.Copy(unitArgs, seedUnitState(t, e))

	got := measuredDoc{Note: measuredNote, Roles: systemRoles(t, e), Verbs: map[string]measuredVerb{}}
	for _, verb := range slices.Sorted(maps.Keys(unitArgs)) {
		tool, args := routedCall(t, verb)
		var row measuredVerb
		for _, role := range got.Roles {
			apptest.AssignRoleTo(t, e, adminEmail, role)
			answer := client.Call(t, tool, args)
			mu.Lock()
			call := recorded[verb]
			delete(recorded, verb)
			mu.Unlock()
			switch apptest.VerdictOf(answer, call.Refused) {
			case apptest.VerdictAllowed:
				row.Allowed = append(row.Allowed, role)
			case apptest.VerdictRefused:
				row.Refused = append(row.Refused, role)
			case apptest.VerdictOpen:
				t.Errorf("%s as %s reached no verdict: %s", verb, role, answer.Text)
			}
			if role == "admin" {
				row.Checks = call.Checks
			}
		}
		if !slices.Contains(row.Allowed, "admin") {
			t.Errorf("%s did not run for the admin, so no refusal of it proves a role gate", verb)
		}
		got.Verbs[verb] = row
	}
	apptest.AssignRoleTo(t, e, adminEmail, "admin")
	holdMeasuredFile(t, got)
}

func systemRoles(t *testing.T, e *apptest.AppEnv) []string {
	t.Helper()
	var keys []string
	for _, role := range apptest.SeededRoles(t, e) {
		keys = append(keys, role.Key)
	}
	if len(keys) == 0 {
		t.Fatal("the database seeds no role, so this measured nothing")
	}
	return keys
}

func holdMeasuredFile(t *testing.T, got measuredDoc) {
	t.Helper()
	rendered, err := json.MarshalIndent(got, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	rendered = append(rendered, '\n')
	if os.Getenv("UPDATE_MCP_TOOL_ROLES") != "" {
		if err := os.WriteFile(measuredFile, rendered, 0o600); err != nil {
			t.Fatal(err)
		}
		return
	}
	committed, err := os.ReadFile(measuredFile)
	if err != nil {
		t.Fatal(err)
	}
	if string(committed) != string(rendered) {
		t.Errorf("%s is not what the roles were answered. Run: UPDATE_MCP_TOOL_ROLES=1 make test-it DIR=backend/internal/compose/integration/extensionrole", measuredFile)
	}
}
