package aicert

// The tier certification table: for each task and each model its records
// measured, the verdict the AI admin screen prints beside a tier binding.
// Generated into internal/modules/ai/tiercert_gen.go from the committed records.

import (
	"bytes"
	"context"
	"fmt"
	"go/format"
	"sort"
	"strings"

	"github.com/margince/margince/backend/internal/compose/aitasks"
	"github.com/margince/margince/backend/internal/modules/ai"
)

const tierCertHeader = `// Code generated by compose/aicert/decisioncertcmd from internal/compose/aicert/records. DO NOT EDIT.
// Regenerate with ` + "`make gen`" + `. A row exists for every task and model a ladder record measures.

package ai
`

// TierCertRow is one row of the generated table.
type TierCertRow struct {
	Key  ai.TierCertKey
	Cert ai.TierCert
}

// TierCertTable is the verdict of every (task, provider, model, profile) the
// committed ladder records measure.
//
// A task's verdict is the worst across its sites, and a site no record of that
// model measured counts as not supported, for the reason rungVerdict gives.
// Records of one model that differ only in thinking level or upstream
// preference share a row, and the worst of them stands: the screen cannot see
// those settings, and the sentence it prints must not be kinder than any record.
func TierCertTable(ctx context.Context, corpus []Scenario, census *aitasks.Registry, records []Record) ([]TierCertRow, error) {
	byTask := map[ai.Task][]Scenario{}
	for _, sc := range corpus {
		byTask[ai.Task(sc.Task)] = append(byTask[ai.Task(sc.Task)], sc)
	}
	var rows []TierCertRow
	for task, scenarios := range byTask {
		readiness, err := readinessOf(ctx, census, task, scenarios, records)
		if err != nil {
			return nil, err
		}
		rows = append(rows, taskTierCerts(scenarios, readiness)...)
	}
	sort.Slice(rows, func(i, j int) bool { return tierCertKeyLess(rows[i].Key, rows[j].Key) })
	return rows, nil
}

func taskTierCerts(scenarios []Scenario, readiness []ReadinessRow) []TierCertRow {
	keys := map[ai.TierCertKey]bool{}
	for _, row := range readiness {
		if row.Certified && row.Record.Kind != KindDecision {
			keys[tierKeyOf(row.Record)] = true
		}
	}
	var rows []TierCertRow
	for key := range keys {
		verdict, status := VerdictCertified, StatusCurrent
		for _, site := range scenarioSites(scenarios) {
			siteVerdict, siteStatus := VerdictNotSupported, StatusAbsent
			measured := false
			for _, row := range readiness {
				if !row.Certified || row.Record.Kind == KindDecision || row.Site.Variant != site || tierKeyOf(row.Record) != key {
					continue
				}
				if !measured || VerdictRank(row.Record.Verdict) < VerdictRank(siteVerdict) {
					siteVerdict = row.Record.Verdict
				}
				if !measured || statusRank[row.Status()] < statusRank[siteStatus] {
					siteStatus = row.Status()
				}
				measured = true
			}
			if VerdictRank(siteVerdict) < VerdictRank(verdict) {
				verdict = siteVerdict
			}
			if statusRank[siteStatus] < statusRank[status] {
				status = siteStatus
			}
		}
		rows = append(rows, TierCertRow{Key: key, Cert: ai.TierCert{Verdict: verdict, Current: status == StatusCurrent}})
	}
	return rows
}

func tierKeyOf(rec Record) ai.TierCertKey {
	return ai.TierCertKey{Task: ai.Task(rec.Task), Provider: rec.Provider, Model: rec.ServedModel, Profile: ai.Profile(rec.EnvClass)}
}

func tierCertKeyLess(a, b ai.TierCertKey) bool {
	if a.Task != b.Task {
		return a.Task < b.Task
	}
	if a.Provider != b.Provider {
		return a.Provider < b.Provider
	}
	if a.Model != b.Model {
		return a.Model < b.Model
	}
	return a.Profile < b.Profile
}

// RenderTierCertTable is the generated file for rows, gofmt'd.
func RenderTierCertTable(rows []TierCertRow) ([]byte, error) {
	var src strings.Builder
	src.WriteString(tierCertHeader)
	src.WriteString("\nvar tierCertified = map[TierCertKey]TierCert{\n")
	for _, row := range rows {
		fmt.Fprintf(&src, "\t{Task: %q, Provider: %q, Model: %q, Profile: %q}: {Verdict: %q, Current: %t},\n",
			row.Key.Task, row.Key.Provider, row.Key.Model, row.Key.Profile, row.Cert.Verdict, row.Cert.Current)
	}
	src.WriteString("}\n")
	formatted, err := format.Source([]byte(src.String()))
	if err != nil {
		return nil, fmt.Errorf("aicert: the tier certification table does not format: %w", err)
	}
	return bytes.Clone(formatted), nil
}
