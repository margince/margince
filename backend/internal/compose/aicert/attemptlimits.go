package aicert

// The per-try limit of each task a user waits on, generated from the committed
// completion records into internal/modules/ai/attemptlimits_gen.go. The limit
// follows the slowest model a record lets serve the task, and the row lists
// every such model: the runtime holds a walk to the limit only while each of
// its rungs is one of them. The drift check fails a committed table the
// records no longer give.

import (
	"bytes"
	"errors"
	"fmt"
	"go/format"
	"slices"
	"sort"
	"strings"
	"time"

	"github.com/margince/margince/backend/internal/modules/ai"
)

const attemptLimitHeader = `// Code generated by compose/aicert/attemptlimitcmd from internal/compose/aicert/records. DO NOT EDIT.
// Regenerate with ` + "`make gen`" + `. One row per interactive task a served cloud record measures: its
// per-try limit, ai.InteractiveAttemptTimeout of the slowest such record's p95 latency, and
// every model such a record measured.

package ai
`

// MeasuredModel is the provider and served model one record measured.
type MeasuredModel struct {
	Provider string
	Model    string
}

// AttemptLimitRow is one interactive task's per-try limit, the record of the
// slowest model that may serve it, and every model a record measured for it.
type AttemptLimitRow struct {
	Task     ai.Task
	Record   string
	Slowest  MeasuredModel
	P95      time.Duration
	Limit    time.Duration
	Measured []MeasuredModel
}

// AttemptLimitRows is one row per interactive task that some served cloud
// record measures, sorted by task.
//
// A record counts when its verdict lets the model serve: certified or
// supported_degraded. A not_supported model is one no installation should be
// bound to, and its p95 often counts the very timeouts that failed it. A local
// model's record does not count: the runtime keeps a local rung at
// CallCeiling. A record counts whether or not its prompt stamp is current,
// since a prompt edit barely moves how long a model takes.
func AttemptLimitRows(records []Record) []AttemptLimitRow {
	byTask := map[ai.Task][]Record{}
	for _, rec := range records {
		task := ai.Task(rec.Task)
		if measuresAWaitedTask(rec, task) {
			byTask[task] = append(byTask[task], rec)
		}
	}
	rows := make([]AttemptLimitRow, 0, len(byTask))
	for task, measured := range byTask {
		rows = append(rows, attemptLimitRow(task, measured))
	}
	sort.Slice(rows, func(i, j int) bool { return rows[i].Task < rows[j].Task })
	return rows
}

func attemptLimitRow(task ai.Task, measured []Record) AttemptLimitRow {
	slowest := measured[0]
	models := make([]MeasuredModel, 0, len(measured))
	for _, rec := range measured {
		if rec.LatencyP95 > slowest.LatencyP95 ||
			(rec.LatencyP95 == slowest.LatencyP95 && recordPath(generatedRecordsDir, rec) < recordPath(generatedRecordsDir, slowest)) {
			slowest = rec
		}
		model := MeasuredModel{Provider: rec.Provider, Model: rec.ServedModel}
		if !slices.Contains(models, model) {
			models = append(models, model)
		}
	}
	sort.Slice(models, func(i, j int) bool {
		return models[i].Provider+"\x00"+models[i].Model < models[j].Provider+"\x00"+models[j].Model
	})
	p95 := time.Duration(slowest.LatencyP95) * time.Millisecond
	return AttemptLimitRow{
		Task: task, Record: recordPath(generatedRecordsDir, slowest), P95: p95, Limit: ai.InteractiveAttemptTimeout(p95),
		Slowest: MeasuredModel{Provider: slowest.Provider, Model: slowest.ServedModel}, Measured: models,
	}
}

func measuresAWaitedTask(rec Record, task ai.Task) bool {
	return rec.Kind == "" && rec.LatencyP95 > 0 && !ai.ProviderIsLocal(rec.Provider) &&
		VerdictRank(rec.Verdict) >= VerdictRank(VerdictSupportedDegraded) &&
		ai.ExecutionModeOf(task) == ai.ExecutionModeInteractive && !ai.LatencyScalesWithInput(task)
}

// RenderAttemptLimits is the generated file for rows, gofmt'd.
func RenderAttemptLimits(rows []AttemptLimitRow) ([]byte, error) {
	var src strings.Builder
	src.WriteString(attemptLimitHeader)
	if len(rows) == 0 {
		src.WriteString("\nvar certifiedAttemptTimeouts = map[Task]certifiedLimit{}\n")
	} else {
		src.WriteString("\nimport \"time\"\n\nvar certifiedAttemptTimeouts = map[Task]certifiedLimit{\n")
		for _, row := range rows {
			fmt.Fprintf(&src, "\t// %s: p95 %s\n", row.Record, row.P95)
			fmt.Fprintf(&src, "\t%q: {limit: %d * time.Second, measured: []boundModel{\n", row.Task, row.Limit/time.Second)
			for _, model := range row.Measured {
				fmt.Fprintf(&src, "\t\t{provider: %q, model: %q},\n", model.Provider, model.Model)
			}
			src.WriteString("\t}},\n")
		}
		src.WriteString("}\n")
	}
	formatted, err := format.Source([]byte(src.String()))
	if err != nil {
		return nil, fmt.Errorf("aicert: the attempt limit table does not format: %w", err)
	}
	return formatted, nil
}

// AttemptLimitDrift compares the committed table with the one rows render. It
// names the lines the records give that the committed table lacks, and the
// committed lines they no longer give.
func AttemptLimitDrift(committed []byte, rows []AttemptLimitRow) error {
	want, err := RenderAttemptLimits(rows)
	if err != nil {
		return err
	}
	if bytes.Equal(committed, want) {
		return nil
	}
	var problems []string
	for _, line := range linesMissingFrom(want, committed) {
		problems = append(problems, "add: "+line)
	}
	for _, line := range linesMissingFrom(committed, want) {
		problems = append(problems, "remove: "+line)
	}
	return errors.New("the attempt limit table is not what the committed records give — run `make gen`" +
		strings.Join(append([]string{""}, problems...), "\n  - "))
}

// linesMissingFrom is each non-blank line of from that other does not hold.
func linesMissingFrom(from, other []byte) []string {
	held := map[string]bool{}
	for line := range strings.SplitSeq(string(other), "\n") {
		held[line] = true
	}
	var missing []string
	for line := range strings.SplitSeq(string(from), "\n") {
		if strings.TrimSpace(line) != "" && !held[line] {
			missing = append(missing, strings.TrimSpace(line))
		}
	}
	return missing
}
