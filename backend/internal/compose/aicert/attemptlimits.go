package aicert

// The per-try limit of each task a user waits on, generated from the committed
// completion records into internal/modules/ai/attemptlimits_gen.go. The limit
// follows the slowest model a record lets serve the task, so a slower record
// raises it at the next `make gen`, and the drift check here fails a committed
// table the records no longer give.

import (
	"bytes"
	"fmt"
	"go/format"
	"sort"
	"strings"
	"time"

	"github.com/margince/margince/backend/internal/modules/ai"
)

const attemptLimitHeader = `// Code generated by compose/aicert/attemptlimitcmd from internal/compose/aicert/records. DO NOT EDIT.
// Regenerate with ` + "`make gen`" + `. One row per interactive task a served record measures: its
// per-try limit, ai.InteractiveAttemptTimeout of the slowest such record's p95 latency.

package ai
`

// AttemptLimitRow is one interactive task's per-try limit and the record of
// the slowest model that may serve it.
type AttemptLimitRow struct {
	Task   ai.Task
	Record string
	P95    time.Duration
	Limit  time.Duration
}

// AttemptLimitRows is one row per interactive task that some served record
// measures, sorted by task.
//
// A record counts when its verdict lets the model serve: certified or
// supported_degraded. A not_supported model is one no installation should be
// bound to, and its p95 often counts the very timeouts that failed it. A record
// counts whether or not its prompt stamp is current: a prompt edit barely moves
// how long a model takes, and a limit that fell back to CallCeiling on every
// edit would come and go with work unrelated to speed.
func AttemptLimitRows(records []Record) []AttemptLimitRow {
	slowest := map[ai.Task]Record{}
	for _, rec := range records {
		task := ai.Task(rec.Task)
		if !measuresAWaitedTask(rec, task) {
			continue
		}
		held, seen := slowest[task]
		if !seen || rec.LatencyP95 > held.LatencyP95 ||
			(rec.LatencyP95 == held.LatencyP95 && recordPath(generatedRecordsDir, rec) < recordPath(generatedRecordsDir, held)) {
			slowest[task] = rec
		}
	}
	rows := make([]AttemptLimitRow, 0, len(slowest))
	for task, rec := range slowest {
		p95 := time.Duration(rec.LatencyP95) * time.Millisecond
		rows = append(rows, AttemptLimitRow{
			Task: task, Record: recordPath(generatedRecordsDir, rec), P95: p95, Limit: ai.InteractiveAttemptTimeout(p95),
		})
	}
	sort.Slice(rows, func(i, j int) bool { return rows[i].Task < rows[j].Task })
	return rows
}

func measuresAWaitedTask(rec Record, task ai.Task) bool {
	return rec.Kind == "" && rec.LatencyP95 > 0 &&
		VerdictRank(rec.Verdict) >= VerdictRank(VerdictSupportedDegraded) &&
		ai.ExecutionModeOf(task) == ai.ExecutionModeInteractive && !ai.LatencyScalesWithInput(task)
}

// RenderAttemptLimits is the generated file for rows, gofmt'd.
func RenderAttemptLimits(rows []AttemptLimitRow) ([]byte, error) {
	var src strings.Builder
	src.WriteString(attemptLimitHeader)
	if len(rows) == 0 {
		src.WriteString("\nvar certifiedAttemptTimeouts = map[Task]time.Duration{}\n")
	} else {
		src.WriteString("\nimport \"time\"\n\nvar certifiedAttemptTimeouts = map[Task]time.Duration{\n")
		for _, row := range rows {
			fmt.Fprintf(&src, "\t// %s: p95 %s\n", row.Record, row.P95)
			fmt.Fprintf(&src, "\t%q: %d * time.Second,\n", row.Task, row.Limit/time.Second)
		}
		src.WriteString("}\n")
	}
	formatted, err := format.Source([]byte(src.String()))
	if err != nil {
		return nil, fmt.Errorf("aicert: the attempt limit table does not format: %w", err)
	}
	return formatted, nil
}

// AttemptLimitDrift compares the committed table with the one rows render,
// naming each line that differs.
func AttemptLimitDrift(committed []byte, rows []AttemptLimitRow) error {
	want, err := RenderAttemptLimits(rows)
	if err != nil {
		return err
	}
	if bytes.Equal(committed, want) {
		return nil
	}
	had := map[string]bool{}
	for line := range strings.SplitSeq(string(committed), "\n") {
		had[line] = true
	}
	var missing []string
	for line := range strings.SplitSeq(string(want), "\n") {
		if !had[line] {
			missing = append(missing, strings.TrimSpace(line))
		}
	}
	return fmt.Errorf("the attempt limit table is not what the committed records give — run `make gen`; the records give%s",
		strings.Join(append([]string{""}, missing...), "\n  + "))
}
