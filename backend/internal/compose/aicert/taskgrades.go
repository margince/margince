package aicert

// The table internal/modules/ai/taskgrades_gen.go holds every completion
// record's grade on its task by the readiness report's rung rule. So the grade
// Settings shows beside a task is the one `make e2e-ai-report` prints.

import (
	"context"
	"fmt"
	"go/format"
	"maps"
	"slices"
	"strings"

	"github.com/margince/margince/backend/internal/compose/aitasks"
	"github.com/margince/margince/backend/internal/modules/ai"
)

// TaskGradeRow is one record's key and grade, and the record file it came from.
type TaskGradeRow struct {
	Key    ai.CertKey
	Grade  ai.CertGrade
	Record string
}

// TaskGrades grades every completion record that still measures a binding this
// build can serve. The binding is the record's own, and RungGrade folds it as
// it folds a preset's rung. A record whose site floors are not the ones this
// build asks measures no binding and earns no row.
func TaskGrades(ctx context.Context, corpus []Scenario, census *aitasks.Registry, records []Record) ([]TaskGradeRow, error) {
	byTask := map[ai.Task][]Scenario{}
	for _, sc := range corpus {
		byTask[ai.Task(sc.Task)] = append(byTask[ai.Task(sc.Task)], sc)
	}
	var out []TaskGradeRow
	for _, task := range slices.Sorted(maps.Keys(byTask)) {
		rows, err := readinessOf(ctx, census, task, byTask[task], records)
		if err != nil {
			return nil, err
		}
		for _, rec := range records {
			if rec.Kind == KindDecision || rec.Task != string(task) {
				continue
			}
			binding := ai.ProviderConfig{
				Provider: rec.Provider, Model: rec.ServedModel, ThinkingLevel: rec.ThinkingLevel, Routing: rec.CandidateUpstream,
			}
			if rec.CandidateUpstream != nil {
				binding.BaseURL = recordBrokerHost
			}
			profile := ai.Profile(rec.EnvClass)
			if !recordMeasures(rec, binding, profile, task) {
				continue
			}
			state, verdict := RungGrade(rows, byTask[task], binding, profile, task)
			out = append(out, TaskGradeRow{
				Key:    recordCertKey(rec),
				Grade:  ai.CertGrade{Verdict: verdict, State: state},
				Record: recordPath(generatedRecordsDir, rec),
			})
		}
	}
	return out, nil
}

// recordBrokerHost stands in for the host of a record served through the
// broker, which the record does not keep. Only an OpenRouter host carries
// upstream preferences, and every one asks the same site floors.
const recordBrokerHost = "https://openrouter.ai/api"

const taskGradesHeader = `// Code generated by compose/aicert/taskgradecmd from internal/compose/aicert/records. DO NOT EDIT.
// Regenerate with ` + "`make gen`" + `. One row per completion record that measures a binding
// this build serves: its worst verdict and worst state over every site its task ships.

package ai
`

// RenderTaskGrades writes the table as Go source.
func RenderTaskGrades(rows []TaskGradeRow) ([]byte, error) {
	var src strings.Builder
	src.WriteString(taskGradesHeader)
	src.WriteString("\nvar taskGrades = map[CertKey]CertGrade{\n")
	for _, row := range rows {
		k := row.Key
		fmt.Fprintf(&src, "\t// %s\n", row.Record)
		fmt.Fprintf(&src, "\t{Task: %q, Provider: %q, Model: %q, Profile: %q, ThinkingLevel: %q, SiteThinking: %q, Upstream: %q}: {Verdict: %q, State: %q},\n",
			k.Task, k.Provider, k.Model, k.Profile, k.ThinkingLevel, k.SiteThinking, k.Upstream, row.Grade.Verdict, row.Grade.State)
	}
	src.WriteString("}\n")
	formatted, err := format.Source([]byte(src.String()))
	if err != nil {
		return nil, fmt.Errorf("aicert: the task grade table does not format: %w", err)
	}
	return formatted, nil
}
